func TestErrorCodesFrozen(t *testing.T) {
	byValue := make(map[int64]string, len(errorCodeSnapshot))
	for name, want := range errorCodeSnapshot {
		if prev, dup := byValue[want]; dup {
			t.Errorf("error code value %d is shared by %s and %s", want, prev, name)
		}
		byValue[want] = name
	}
}

